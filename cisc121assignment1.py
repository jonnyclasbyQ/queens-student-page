# Question 9: Missing Integer
def solution(A): # Define the function
  if min(A)>1: # A case that returns 1
    return 1
  if max(A)<0: # Another case that returns 1
    return 1
  else:
    for i in range(min(A), max(A)): # Checking each number in the range of min, max
      if i not in A and i > 0: # If one of those numbers is missing
        return i # It is our value
    return max(A) + 1 # Else, our set spans [1, max(A)]

