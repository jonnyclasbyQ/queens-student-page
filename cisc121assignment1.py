# Question 7: Frog River One
def solution(A, x):
    # Track the unique positions where leaves have fallen
    seen = set()

    # Iterate through the array to check each second (i) and leaf position (num)
    for i, num in enumerate(A):
        # Only track leaves that fall within the required path (1 to x)
        if 1 <= num <= x:
            seen.add(num)

        # If we have found leaves for every position from 1 to x,
        # the frog can cross at this current second (i)
        if len(seen) == x:
            return i

    # Return -1 if the frog can never cross (not all positions received a leaf)
    return -1

# Question 8: Passing Cars
def passing_cars(nums): #Define the function
    east_count = 0 #Count the number of cars eastbound
    total_pairs = 0 #Count the number of pairs

    for num in nums: #Iterate through each number
        if num == 0:
            east_count += 1 #If a number is eastbound increase east_count
        else: # If a number is westbound
            total_pairs += east_count #We add the number of cars eastbound, which are west of that car

        if total_pairs > 1_000_000_000: #Exception case
            return -1

    return total_pairs #Provides the output